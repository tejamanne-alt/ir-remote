def lg_checksum(f):
    return sum((f >> s) & 0xF for s in (0, 4, 8, 12)) & 0xF


class Parser:
    def __init__(self, text):
        self.s = re.sub(r'\s+', '', text)
        self.i = 0

    def peek(self):
        return self.s[self.i] if self.i < len(self.s) else ''

    def eat(self, ch):
        if self.peek() != ch:
            raise ValueError('expected %r at %d in %s' % (ch, self.i, self.s))
        self.i += 1

    def number(self):
        m = re.match(r'\d+(\.\d+)?', self.s[self.i:])
        if not m:
            raise ValueError('number expected at %d' % self.i)
        self.i += len(m.group(0))
        return float(m.group(0))

    def general(self):
        self.eat('{')
        spec = {'carrier': 38000.0, 'unit': 1.0, 'msb': False}
        while True:
            if self.s[self.i:self.i + 3] == 'msb':
                self.i += 3
                spec['msb'] = True
            else:
                n = self.number()
                if self.peek() == 'k':
                    self.i += 1
                    spec['carrier'] = n * 1000
                else:
                    spec['unit'] = n
            if self.peek() == ',':
                self.i += 1
                continue
            self.eat('}')
            return spec

    def bitspec(self):
        self.eat('<')
        symbols = [[]]
        while True:
            neg = False
            if self.peek() == '-':
                neg = True
                self.i += 1
            n = self.number()
            symbols[-1].append(-n if neg else n)
            c = self.peek()
            self.i += 1
            if c == ',':
                continue
            if c == '|':
                symbols.append([])
                continue
            if c == '>':
                return symbols
            raise ValueError('bad bitspec')

    def expr(self):
        # expr := term (('^'|'+'|'-') term)*   (left to right; enough here)
        node = self.term()
        while self.peek() in ('^', '+', '-'):
            op = self.peek()
            self.i += 1
            node = ('op', op, node, self.term())
        return node

    def term(self):
        c = self.peek()
        if c == '~':
            self.i += 1
            return ('not', self.term())
        if c == '(':
            self.eat('(')
            e = self.expr()
            self.eat(')')
            return e
        if c.isdigit():
            return ('num', int(self.number()))
        m = re.match(r'[A-Z]', self.s[self.i:])
        if not m:
            raise ValueError('term expected at %d' % self.i)
        self.i += 1
        return ('var', m.group(0))

    def irstream(self):
        self.eat('(')
        items = []
        while True:
            items.append(self.item())
            if self.peek() == ',':
                self.i += 1
                continue
            self.eat(')')
            break
        rep = ''
        if self.peek() in ('+', '*'):
            rep = self.peek()
            self.i += 1
        return ('stream', items, rep)

    def item(self):
        c = self.peek()
        if c == '(':
            # either a nested stream or a parenthesised expression bitfield
            save = self.i
            try:
                e = self.expr()
                if self.peek() == ':':
                    return self.bitfield_rest(e)
            except ValueError:
                pass
            self.i = save
            return self.irstream()
        if c == '<':
            bs = self.bitspec()
            st = self.irstream()
            return ('bitspec_stream', bs, st)
        if c == '^':
            self.i += 1
            n = self.number()
            return ('extent', self.suffix(n))
        if c == '-':
            self.i += 1
            n = self.number()
            kind, v = self.suffix_units(n)
            return ('dur', kind, -v)
        if c.isdigit():
            save = self.i
            e = self.expr()
            if self.peek() == ':':
                return self.bitfield_rest(e)
            self.i = save
            n = self.number()
            kind, v = self.suffix_units(n)
            return ('dur', kind, v)
        e = self.expr()
        return self.bitfield_rest(e)

    def suffix(self, n):
        # extent: always absolute time
        if self.peek() == 'm':
            self.i += 1
            return ('abs', n * 1000)
        if self.peek() == 'u':
            self.i += 1
            return ('abs', n)
        return ('units', n)

    def suffix_units(self, n):
        if self.peek() == 'm':
            self.i += 1
            return ('abs', n * 1000)
        if self.peek() == 'u':
            self.i += 1
            return ('abs', n)
        return ('units', n)

    def bitfield_rest(self, e):
        self.eat(':')
        width = int(self.number())
        offset = 0
        if self.peek() == ':':
            self.i += 1
            offset = int(self.number())
        return ('field', e, width, offset)


def evaluate(node, env):
    kind = node[0]
    if kind == 'num':
        return node[1]
    if kind == 'var':
        return env[node[1]]
    if kind == 'not':
        return ~evaluate(node[1], env)
    if kind == 'op':
        a = evaluate(node[2], env)
        b = evaluate(node[3], env)
        return {'^': a ^ b, '+': a + b, '-': a - b}[node[1]]
    raise ValueError(kind)


def run_stream(stream, spec, bits, env, out, first_pass):
    """Appends signed microsecond durations for one pass of [stream]."""
    _, items, rep = stream
    start = sum(abs(x) for x in out)
    for it in items:
        k = it[0]
        if k == 'dur':
            _, kind, n = it
            out.append(n * spec['unit'] if kind == 'units' else n)
        elif k == 'extent':
            kind, n = it[1]
            target = n * spec['unit'] if kind == 'units' else n
            elapsed = sum(abs(x) for x in out) - start
            out.append(-(target - elapsed))
        elif k == 'field':
            value = (evaluate(it[1], env) >> it[3]) & ((1 << it[2]) - 1)
            order = range(it[2] - 1, -1, -1) if spec['msb'] else range(it[2])
            for b in order:
                for d in bits[(value >> b) & 1]:
                    out.append(d * spec['unit'])
        elif k == 'bitspec_stream':
            run_stream(it[2], spec, it[1], env, out, first_pass)
        elif k == 'stream':
            # nested repeating stream: one pass belongs to the first pass;
            # the repeat part is extracted separately
            if first_pass and it[2] == '*':
                continue  # zero-or-more: not part of the first pass
            run_stream(it, spec, bits, env, out, first_pass)
    return out


def merge(seq):
    merged = []
    for d in seq:
        if d == 0:
            continue
        if merged and (merged[-1] > 0) == (d > 0):
            merged[-1] += d
        else:
            merged.append(d)
    return merged


def strip(seq):
    """Returns (leading space, frame marks/spaces, trailing space)."""
    m = merge(seq)
    lead = -m.pop(0) if m and m[0] < 0 else 0
    trail = -m.pop() if m and m[-1] < 0 else 0
    return lead, m, trail


def find_repeat_stream(stream):
    _, items, rep = stream
    for it in items:
        if it[0] == 'stream':
            return it
        if it[0] == 'bitspec_stream' and it[2][2]:
            return it[2]
    return None


def generate(irp, params):
    p = Parser(irp)
    spec = p.general()
    bits = p.bitspec()
    top = p.irstream()
    main = strip(run_stream(top, spec, bits, params, [], True))
    inner = find_repeat_stream(top)
    if inner is not None:
        rep_stream = ('stream', inner[1], '')
    else:
        rep_stream = ('stream', top[1], '')
    rep = strip(run_stream(rep_stream, spec, bits, params, [], False))
    frame = [round(abs(x)) for x in main[1]]
    rframe = [round(abs(x)) for x in rep[1]]
    return {
        'carrierHz': round(spec['carrier']),
        'durationsUs': frame,
        'repeat': {
            'frameUs': rframe,
            'leadInGapUs': round(main[2] + rep[0]),
            'gapUs': round(rep[2] + rep[0]),
        },
    }


def build_all():
    files = {}
    for pid, irp, source, min_repeats, cases in PROTOCOLS:
        for name, params in cases:
            env = dict(params)
            if pid == 'LG':
                env['C'] = lg_checksum(params['F'])
            sig = generate(irp, env)
            if min_repeats:
                sig['repeat']['minRepeats'] = min_repeats
            doc = {
                'protocol': pid,
                'params': params,
                'carrierHz': sig['carrierHz'],
                'durationsUs': sig['durationsUs'],
                'repeat': sig['repeat'],
                'source': '%s; IRP %s; generated by tools/fixtures/irp_oracle.py' % (source, irp),
            }
            files[os.path.join(OUT, pid, name + '.json')] = json.dumps(doc, indent=2, sort_keys=True) + '\n'
    return files


def main():
    check = '--check' in sys.argv
    files = build_all()
    bad = 0
    for path, text in sorted(files.items()):
        if check:
            try:
                with open(path) as f:
                    if f.read() != text:
                        print('stale fixture:', os.path.relpath(path, ROOT))
                        bad += 1
            except FileNotFoundError:
                print('missing fixture:', os.path.relpath(path, ROOT))
                bad += 1
        else:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, 'w') as f:
                f.write(text)
    if check:
        print('%d fixtures checked, %d problems' % (len(files), bad))
        sys.exit(1 if bad else 0)
    print('wrote %d fixtures' % len(files))


if __name__ == '__main__':
    main()
