"""Independent golden-fixture generator for ir_core codecs.

Evaluates published IRP notation strings (JP1 / hifi-remote DecodeIR protocol
list, http://www.hifi-remote.com/wiki/index.php/DecodeIR) with a small generic
interpreter that knows nothing about individual protocols. The Dart codecs are
then tested against these timings, so a codec bug cannot hide behind fixtures
generated by the codec itself.

Supported IRP subset: general spec {carrier,unit,msb}, bitspecs <a|b>, nested
bitspec-irstreams, durations in units or with m/u suffix, extents (^108m),
bitfields value:width[:offset] with ~ complement, expressions with ^ + - and
parentheses, repeat markers + and *.

Usage: python3 tools/fixtures/irp_oracle.py [--check]
Writes packages/ir_core/test/fixtures/<protocol>/<case>.json. With --check it
regenerates in memory and exits 1 if any committed fixture differs.
"""

